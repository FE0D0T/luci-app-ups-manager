'use strict';
'require view';
'require form';
'require ui';

return view.extend({
	render: function() {
		var m, s, o;

		m = new form.Map('ups_manager', _('Защита при отключении питания и согласованное выключение'),
			_('При отключении сети или перед полным разрядом батареи безопасно выключаются NAS и серверы в локальной сети в порядке приоритета, а маршрутизатор выключается последним.'));

		s = m.section(form.NamedSection, 'shutdown', 'shutdown_policy', _('Условия срабатывания защиты выключения'));
		s.anonymous = true;

		o = s.option(form.Flag, 'enabled', _('Включить автоматическую защиту выключения'));
		o.default = '1';

		o = s.option(form.Value, 'battery_low_percent', _('Заряд батареи для выключения (%)'),
			_('Когда заряд батареи в процентах становится меньше или равен этому значению, немедленно запускается согласованное выключение.'));
		o.datatype = 'uinteger';
		o.default = '20';

		o = s.option(form.Value, 'runtime_low_seconds', _('Расчётное время работы для выключения (сек)'),
			_('Выключение запускается, когда расчётное время работы от батареи меньше этого значения (например, 300 сек = 5 мин).'));
		o.datatype = 'uinteger';
		o.default = '300';

		o = s.option(form.Value, 'on_battery_delay', _('Максимальное время работы от батареи (сек)'),
			_('Выключение запускается, если работа от батареи длится дольше этого времени. 0 означает без ограничения времени, решение принимается только по заряду и времени работы.'));
		o.datatype = 'uinteger';
		o.default = '600';

		s = m.section(form.NamedSection, 'shutdown', 'shutdown_policy', _('Приоритет и порядок отключения устройств'));
		s.anonymous = true;

		o = s.option(form.Value, 'router_delay', _('Время ожидания перед выключением маршрутизатора (сек)'),
			_('После рассылки команды выключения подчинённым устройствам маршрутизатор ждёт это время (для NAS, PVE и физических серверов, которые сбрасывают данные на диск), а затем выключается сам.'));
		o.datatype = 'uinteger';
		o.default = '180';

		o = s.option(form.Flag, 'shutdown_router', _('Выключать систему маршрутизатора'));
		o.default = '1';

		// High risk option with confirmation
		o = s.option(form.Flag, 'poweroff_ups', _('Полностью отключить выход ИБП (опасная опция)'),
			_('⚠️ Внимание: если включить эту опцию, ИБП получит команду отключить нагрузку в момент выключения маршрутизатора. Если сеть вернётся именно в этот момент, некоторые ИБП останутся выключенными до ручного включения. Для домашних и необслуживаемых установок рекомендуется оставить выключенным!'));
		o.default = '0';

		return m.render();
	}
});
